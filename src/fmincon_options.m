function options = fmincon_options(cfg, maxIterations, specifyGradient)
%FMINCON_OPTIONS fmincon settings (paper Table 3).
options = optimoptions('fmincon', ...
    'Algorithm', 'interior-point', ...
    'SpecifyObjectiveGradient', specifyGradient, ...
    'CheckGradients', false, ...
    'ScaleProblem', false, ...
    'Display', 'off', ...
    'OptimalityTolerance', cfg.opt.OptimalityTolerance, ...
    'StepTolerance', cfg.opt.StepTolerance, ...
    'MaxIterations', maxIterations);
end
